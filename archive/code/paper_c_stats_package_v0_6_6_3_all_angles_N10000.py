    def run_paper_b_geometries_suite(self, meas_angle=10.0, n_sample=10000):
        """
        Executes the 12-test statistical suite across all three Paper B detector pitches:
        dx = 150 mm (gs=3), dx = 50 mm (gs=9), dx = 5 mm (gs=89).
        Outputs complete tables directly to terminal stdout and records to file.
        """
        geoms = [(150, 3), (50, 9), (5, 89)]
        out_path = "data/stats_paper_b_geometries_n10k.txt"

        if self.rank == 0:
            import os
            os.makedirs("data", exist_ok=True)
            f_out = open(out_path, "w")
            f_out.write(f"# Paper B Geometries 12-Test Suite (N={n_sample}, theta={meas_angle} deg)\n")
            print("\n" + "#" * 86)
            print(f"### FULL 12-TEST SUITE ACROSS PAPER B GEOMETRIES (N = {n_sample}, Target = {meas_angle}°) ###")
            print("#" * 86)

        for dx, gs in geoms:
            self.set_geometry(dx, gs)
            if self.rank == 0:
                usable_pct = (len(self.usable_coords) / len(self.coords)) * 100.0
                k_disjoint = len(self.usable_coords) // n_sample
                title = f"GEOMETRY: dx = {dx:3d} mm | gs = {gs:2d}x{gs:2d} | Usable = {len(self.usable_coords)} ({usable_pct:.2f}%) | Max Disjoint = {k_disjoint}"

                # Draw 3 disjoint samples for M, A, B
                sample_M = self.get_disjoint_sample(n_sample, batch_idx=0)
                sample_A = self.get_disjoint_sample(n_sample, batch_idx=1)
                sample_B = self.get_disjoint_sample(n_sample, batch_idx=2)

                xm, ym = self.rotateCoords(sample_M[:, 0], sample_M[:, 1], meas_angle)
                xa, ya = self.rotateCoords(sample_A[:, 0], sample_A[:, 1], 0.0)
                xb, yb = self.rotateCoords(sample_B[:, 0], sample_B[:, 1], 45.0)

                grid_M = self.binEvents(xm, ym) * n_sample
                grid_A = self.binEvents(xa, ya) * n_sample
                grid_B = self.binEvents(xb, yb) * n_sample

                flat_M = np.roll(np.rot90(grid_M).ravel(), -1)
                flat_A = np.roll(np.rot90(grid_A).ravel(), -1)
                flat_B = np.roll(np.rot90(grid_B).ravel(), -1)

                res = self.evaluate_12_tests(flat_M, flat_A, flat_B, grid_M)
                self.print_12_tests_table(res, title=title)
                f_out.write(f"\n{title}\n")
                f_out.write(f"EMD: {res['emd'][0]:.4f} (vs A), {res['emd'][1]:.4f} (vs B)\n")
                f_out.write(f"KL:  {res['kl'][0]:.6f} (vs A), {res['kl'][1]:.6f} (vs B)\n")
                f_out.write(f"Watson: {res['watson'][0]:.4f} (vs A), {res['watson'][2]:.4f} (vs B)\n")

        if self.rank == 0:
            f_out.close()
            print(f"\nArchived Paper B geometry results to: {out_path}\n")
        self.comm.Barrier()

    def run_count_scaling_suite(self, meas_angle=10.0):
        """
        Evaluates count scaling across N in [1, 10, 100, 300, 1000, 10000, 100000]
        for all three Paper B pitches. Tracks FND reconstruction, Definition I
        (Hemisphere/Quadrant alignment), and Definition II (Metrological resolution).
        Safely broadcasts usable event counts and reference grids from Rank 0.
        """
        geoms = [(150, 3), (50, 9), (5, 89)]
        counts = [1, 10, 100, 300, 1000, 10000, 100000]
        out_path = "data/stats_count_scaling_all_geoms.txt"

        if self.rank == 0:
            import os
            os.makedirs("data", exist_ok=True)
            f_out = open(out_path, "w")
            f_out.write(f"# Granular Count Scaling Suite (Target = {meas_angle} deg)\n")
            print("\n" + "#" * 102)
            print(f"### GRANULAR COUNT SCALING SUITE (N = 1 to 100k, Target = {meas_angle}°) ###")
            print("#" * 102)

        for dx, gs in geoms:
            self.set_geometry(dx, gs)

            # Rank 0 determines usable count; worker ranks receive via broadcast
            usable_tot = len(self.usable_coords) if (self.rank == 0 and hasattr(self, 'usable_coords')) else 0
            usable_tot = self.comm.bcast(usable_tot, root=0)

            if self.rank == 0:
                print(f"\n=================== GEOMETRY: dx = {dx} mm (gs = {gs}x{gs}) | Total Usable = {usable_tot} ===================")
                print(f"{'N':<7} | {'FND RECON':<11} | {'DEF I (HEMI / QUAD)':<20} | {'EMD (0° / 45°)':<18} | {'KL (0° / 45°)':<18} | {'WATSON U² (0° / 45°)'}")
                print("-" * 102)
                f_out.write(f"\n--- dx = {dx} mm, gs = {gs} ---\n")

            # Reference grid generated from high-statistics baseline on Rank 0
            if self.rank == 0:
                n_ref = min(10000, usable_tot)
                ref_sample = self.get_disjoint_sample(n_ref, batch_idx=0)
                ref_grid = self.binEvents(ref_sample[:, 0], ref_sample[:, 1])
            else:
                ref_grid = None
            ref_grid = self.comm.bcast(ref_grid, root=0)

            for N in counts:
                if N > usable_tot:
                    continue

                # Rank 0 draws measurement sample and broadcasts to MPI ranks for FND
                meas_sample = self.get_disjoint_sample(N, batch_idx=1) if self.rank == 0 else None
                meas_sample = self.comm.bcast(meas_sample, root=0)

                xm, ym = self.rotateCoords(meas_sample[:, 0], meas_sample[:, 1], meas_angle)
                meas_coords = np.column_stack([xm, ym, meas_sample[:, 2]])

                # FND parallel evaluation across all 30 ranks
                local_norms = []
                for th in self.angles:
                    xr, yr = self.rotateCoords(meas_coords[:, 0], meas_coords[:, 1], th)
                    rot_grid = self.binEvents(xr, yr)
                    local_norms.append(np.linalg.norm(ref_grid - rot_grid))

                all_norms = self.comm.gather(local_norms, root=0)

                if self.rank == 0:
                    stitched = [v for sl in all_norms for v in sl]
                    theta_fnd = float(-self.all_angles[np.argmin(stitched)])

                    # Definition I: Initial Detection Alignment criteria
                    ang_err = abs(((theta_fnd - meas_angle + 180.0) % 360.0) - 180.0)
                    in_hemi = "YES" if ang_err <= 90.0 else "NO"
                    in_quad = "YES" if ang_err <= 45.0 else "NO"
                    def_I_str = f"{in_hemi} / {in_quad}"

                    # Reference comparisons for 12-test metrics
                    sample_A = self.get_disjoint_sample(N, batch_idx=2)
                    sample_B = self.get_disjoint_sample(N, batch_idx=3)

                    xa, ya = self.rotateCoords(sample_A[:, 0], sample_A[:, 1], 0.0)
                    xb, yb = self.rotateCoords(sample_B[:, 0], sample_B[:, 1], 45.0)

                    grid_M = self.binEvents(xm, ym) * N
                    grid_A = self.binEvents(xa, ya) * N
                    grid_B = self.binEvents(xb, yb) * N

                    flat_M = np.roll(np.rot90(grid_M).ravel(), -1)
                    flat_A = np.roll(np.rot90(grid_A).ravel(), -1)
                    flat_B = np.roll(np.rot90(grid_B).ravel(), -1)

                    res = self.evaluate_12_tests(flat_M, flat_A, flat_B, grid_M)

                    emd_s = f"{res['emd'][0]:.2f} / {res['emd'][1]:.2f}"
