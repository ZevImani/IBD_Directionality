    def run_angle_variance_suite(self, n_sample=10000, n_disjoint=30, angle_step=1.0, angle_max=45.0):
        """
        Sweeps target angles from 0 to angle_max deg (1 deg resolution) across K disjoint sets
        for ALL THREE Paper B geometries (dx in [150, 50, 5] mm).
        Tracks FND reconstruction, Definition I quadrant alignment, Centroid angle,
        EMD, KL divergence, and Watson U2 circular statistics.
        """
        import os, sys
        from scipy.stats import wasserstein_distance
        from scipy.special import rel_entr
        from scipy.spatial.distance import mahalanobis
        try:
            from pycircstat2 import Circular
            from pycircstat2.hypothesis import watson_u2_test
            has_circ = True
        except ImportError:
            has_circ = False

        geoms = [(150, 3), (50, 9), (5, 89)]
        test_angles = np.arange(0.0, angle_max + 0.5 * angle_step, angle_step)
        out_path = f"data/stats_angle_variance_all_geoms_N{n_sample}.txt"

        if self.rank == 0:
            os.makedirs("data", exist_ok=True)
            f_out = open(out_path, "w")
            print(f"# All-Angle Variance Suite: N={n_sample}, K={n_disjoint}, Step={angle_step} deg", file=f_out)
            print("# dx_mm\tth_true\tFND_mean\tFND_std\tDef1_pct\tCent_mean\tCent_std\tEMD_mean\tEMD_std\tKL_mean\tKL_std\tWatson_mean\tWatson_std", file=f_out)
            f_out.flush()
            print("\n" + "#" * 118)
            print(f"### FULL ANGLE VARIANCE SWEEP (0° to {angle_max}°, Step = {angle_step}°, N = {n_sample}, K = {n_disjoint} Disjoint Sets) ###")
            print("#" * 118)

        for dx, gs in geoms:
            self.set_geometry(dx, gs)

            usable_tot = len(self.usable_coords) if (self.rank == 0 and hasattr(self, 'usable_coords')) else 0
            usable_tot = self.comm.bcast(usable_tot, root=0)

            k_avail = usable_tot // n_sample
            k_eval = min(n_disjoint, max(1, k_avail - 1))

            if self.rank == 0:
                print(f"\n=================== GEOMETRY: dx = {dx:3d} mm (gs = {gs:2d}x{gs:2d}) | Total Usable = {usable_tot} | Evaluating K = {k_eval} Sets ===================")
                print(f"{'THETA':<6} | {'FND RECON (mean ± std)':<22} | {'DEF I QUAD':<10} | {'CENTROID (mean ± std)':<22} | {'EMD (mean ± std)':<18} | {'KL (mean ± std)':<18} | {'WATSON U²'}")
                print("-" * 118)
                print(f"\n--- dx = {dx} mm, gs = {gs} ---", file=f_out)
                f_out.flush()

            # Reference baseline grid generated from batch 0
            if self.rank == 0:
                ref_sample = self.get_disjoint_sample(n_sample, batch_idx=0)
                ref_grid = self.binEvents(ref_sample[:, 0], ref_sample[:, 1])
                flat_ref = np.roll(np.rot90(ref_grid * n_sample).ravel(), -1)
                norm_ref = (flat_ref / np.sum(flat_ref)) + 1e-6
            else:
                ref_grid, flat_ref, norm_ref = None, None, None

            ref_grid = self.comm.bcast(ref_grid, root=0)
            flat_ref = self.comm.bcast(flat_ref, root=0)
            norm_ref = self.comm.bcast(norm_ref, root=0)

            angles_c = np.linspace(0, 2 * np.pi, len(flat_ref), endpoint=False)
            w_ref = np.maximum(0, flat_ref.astype(int))
            c_ref = Circular(data=np.repeat(angles_c, w_ref), kwargs_median={'method': None}) if has_circ else None

            half_cells = gs // 2

            for th in test_angles:
                fnd_recons, cent_recons = [], []
                emds, kls, watsons = [], [], []
                quad_success = 0

                for k in range(1, k_eval + 1):
                    sample_k = self.get_disjoint_sample(n_sample, batch_idx=k) if self.rank == 0 else None
                    sample_k = self.comm.bcast(sample_k, root=0)

                    xk, yk = self.rotateCoords(sample_k[:, 0], sample_k[:, 1], th)
                    meas_coords = np.column_stack([xk, yk, sample_k[:, 2]])

                    # Parallel FND rotation search across 30 MPI ranks
                    local_norms = []
                    for trial_th in self.angles:
                        xr, yr = self.rotateCoords(meas_coords[:, 0], meas_coords[:, 1], trial_th)
                        rot_grid = self.binEvents(xr, yr)
                        local_norms.append(np.linalg.norm(ref_grid - rot_grid))

                    all_norms = self.comm.gather(local_norms, root=0)

                    if self.rank == 0:
                        stitched = [v for sl in all_norms for v in sl]
                        th_fnd = float(-self.all_angles[np.argmin(stitched)])
                        fnd_recons.append(th_fnd)

                        # Definition I: Quadrant alignment check (|err| <= 45 deg)
                        err_fnd = abs(((th_fnd - th + 180.0) % 360.0) - 180.0)
                        if err_fnd <= 45.0:
                            quad_success += 1

                        # Centroid vector sum
                        grid_k = self.binEvents(xk, yk) * n_sample
                        xc = (np.arange(gs) - half_cells) * dx
                        yc = (np.arange(gs) - half_cells) * dx
                        x_cent = np.sum(np.sum(grid_k, axis=0) * xc)
                        y_cent = np.sum(np.sum(grid_k, axis=1) * yc)
                        cent_recons.append(float(np.rad2deg(np.arctan2(y_cent, x_cent))))

                        # Binned metric comparisons
                        flat_k = np.roll(np.rot90(grid_k).ravel(), -1)
                        norm_k = (flat_k / np.sum(flat_k)) + 1e-6

                        emds.append(wasserstein_distance(flat_k, flat_ref))
                        kls.append(np.sum(rel_entr(norm_k, norm_ref)))

                        if has_circ:
                            try:
                                w_k = np.maximum(0, flat_k.astype(int))
                                c_k = Circular(data=np.repeat(angles_c, w_k), kwargs_median={'method': None})
                                res_u2 = watson_u2_test([c_k, c_ref])
                                u2_val = getattr(res_u2, 'statistic', getattr(res_u2, 'u2', getattr(res_u2, 'U2', None)))
                                watsons.append(float(u2_val) if u2_val is not None else np.nan)
                            except Exception:
                                watsons.append(np.nan)

                if self.rank == 0:
                    # Circular stats for angular parameters
                    def circ_moments(deg_arr):
                        rad = np.deg2rad(deg_arr)
                        m_rad = np.arctan2(np.mean(np.sin(rad)), np.mean(np.cos(rad)))
                        R = np.sqrt(np.mean(np.sin(rad))**2 + np.mean(np.cos(rad))**2)
                        s_deg = np.rad2deg(np.sqrt(max(0.0, -2.0 * np.log(max(1e-6, R)))))
                        return float(np.rad2deg(m_rad)), float(s_deg)

                    fnd_m, fnd_s = circ_moments(fnd_recons)
                    cent_m, cent_s = circ_moments(cent_recons)
                    quad_pct = (quad_success / k_eval) * 100.0

                    emd_m, emd_s = float(np.mean(emds)), float(np.std(emds))
                    kl_m, kl_s = float(np.mean(kls)), float(np.std(kls))
                    wat_m, wat_s = float(np.nanmean(watsons)), float(np.nanstd(watsons))

                    row_str = f"{th:4.1f}° | {fnd_m:5.1f}° ± {fnd_s:4.1f}°       | {quad_pct:5.1f}%    | {cent_m:5.1f}° ± {cent_s:4.1f}°       | {emd_m:7.2f} ± {emd_s:5.2f}  | {kl_m:7.4f} ± {kl_s:6.4f}  | {wat_m:7.3f} ± {wat_s:6.3f}"
                    print(row_str)
                    sys.stdout.flush()

                    print(f"{dx}\t{th}\t{fnd_m}\t{fnd_s}\t{quad_pct}\t{cent_m}\t{cent_s}\t{emd_m}\t{emd_s}\t{kl_m}\t{kl_s}\t{wat_m}\t{wat_s}", file=f_out)
                    f_out.flush()

            if self.rank == 0:
                print("-" * 118)

        if self.rank == 0:
            f_out.close()
            print(f"\nArchived all-angle variance dataset to: {out_path}\n")
        self.comm.Barrier()

    def run_algorithm_benchmark(self, target_angle=10.0, n_sample=10000):
        """
        Executes a head-to-head comparison across directional reconstruction algorithms
        using a common event sample:
          1. Discrete FND (Argmin)
          2. Continuous FND (Absolute Sine Fit)
          3. First Moment / Centroid Vector Sum
          4. 2D Gaussian Surface Centroid Fit
        """
        if self.rank == 0:
            print(f"\n=== Running Directional Algorithm Benchmark (Target Angle = {target_angle}°, N = {n_sample}) ===")

        # 1. Host samples 2*N coordinates (half reference, half target) and broadcasts
        data = self.sampleData(2 * n_sample, center=False) if self.rank == 0 else None
        data = self.comm.bcast(data, root=0)

        half = n_sample
        ref_sample  = data[:half]
        meas_sample = data[half:2 * half]

        # Rotate measurement sample to target angle
        xm, ym = self.rotateCoords(meas_sample[:, 0], meas_sample[:, 1], target_angle)
        meas_coords = np.column_stack([xm, ym, meas_sample[:, 2]])

        # -------------------------------------------------------------
        # Algorithm 1 & 2: Discrete FND (Argmin) and Continuous FND (Sine Fit)
        # -------------------------------------------------------------
        t0_fnd = time.time()
        ref_grid = self.binEvents(ref_sample[:, 0], ref_sample[:, 1])

        local_norms = []
        for theta in self.angles:
            xr, yr = self.rotateCoords(meas_coords[:, 0], meas_coords[:, 1], theta)
            rot_grid = self.binEvents(xr, yr)
            local_norms.append(np.linalg.norm(ref_grid - rot_grid))

        all_norms = self.comm.gather(local_norms, root=0)
        t_fnd_elapsed = time.time() - t0_fnd

        theta_fnd_argmin = np.nan
        theta_fnd_sine = np.nan

        if self.rank == 0:
            stitched_norms = [val for sublist in all_norms for val in sublist]

            # FND compensation rotation: theta_rot + theta_beam = 0 => theta_beam = -theta_rot
            best_idx = np.argmin(stitched_norms)
            theta_fnd_argmin = float(-self.all_angles[best_idx])

            # Continuous |sin| fit
            try:
                popt_sin, _ = curve_fit(
                    self.abs_sine, self.all_angles, stitched_norms,
                    p0=[-target_angle, np.max(stitched_norms) - np.min(stitched_norms), np.min(stitched_norms)],
                    bounds=([-180.0, 0.0, 0.0], [180.0, 5.0, 5.0]),
                    maxfev=5000
                )
                theta_fnd_sine = float(-self.wrap_angle(popt_sin[0]))
            except Exception:
                theta_fnd_sine = np.nan

        # -------------------------------------------------------------
        # Algorithm 3: First Moment / Centroid Vector Sum
        # -------------------------------------------------------------
        theta_centroid = np.nan
        t_centroid_elapsed = 0.0

        if self.rank == 0:
            t0_cent = time.time()
            grid_m = self.binEvents(meas_coords[:, 0], meas_coords[:, 1]) * n_sample

            half_cells = self.grid_size // 2
            x_cent = 0.0
            y_cent = 0.0
            for i in range(self.grid_size):
                for j in range(self.grid_size):
                    # Standard Cartesian coordinates: row i along +y, col j along +x
                    xc = (j - half_cells) * self.seg_size
                    yc = (i - half_cells) * self.seg_size
                    x_cent += grid_m[i, j] * xc
                    y_cent += grid_m[i, j] * yc

            theta_centroid = float(np.rad2deg(np.arctan2(y_cent, x_cent)))
            t_centroid_elapsed = time.time() - t0_cent

        # -------------------------------------------------------------
        # Algorithm 4: 2D Gaussian Surface Centroid Fit
        # -------------------------------------------------------------
        theta_gauss = np.nan
        t_gauss_elapsed = 0.0

        if self.rank == 0:
            t0_gauss = time.time()
            
            # Gabe's normalDistFit protocol: 25x25 spatial binning over aperture [-l, l]
            nbins_g = 25
            hist_g, xedges_g, yedges_g = np.histogram2d(
                meas_coords[:, 0], meas_coords[:, 1],
                bins=nbins_g, range=[[-self.l, self.l], [-self.l, self.l]]
            )
            x_c = 0.5 * (xedges_g[:-1] + xedges_g[1:])
            y_c = 0.5 * (yedges_g[:-1] + yedges_g[1:])
            X_g, Y_g = np.meshgrid(x_c, y_c, indexing="ij")

            x_data = X_g.ravel()
            y_data = Y_g.ravel()
            z_data = hist_g.ravel()

            A_guess = float(np.max(z_data))
            mu_x_guess = float(np.mean(meas_coords[:, 0]))
            mu_y_guess = float(np.mean(meas_coords[:, 1]))
            sigma_guess = float(np.std(meas_coords[:, 0]))
            
            p0_gauss = (A_guess, mu_x_guess, mu_y_guess, sigma_guess, sigma_guess)
            bounds_gauss = ([0.0, -self.l, -self.l, 5.0, 5.0], [np.inf, self.l, self.l, 2.0 * self.l, 2.0 * self.l])

            try:
                popt_g, _ = curve_fit(self.gaussian_2d, (x_data, y_data), z_data, p0=p0_gauss, bounds=bounds_gauss, maxfev=5000)
                mu_x_fit, mu_y_fit = popt_g[1], popt_g[2]
                theta_gauss = float(np.rad2deg(np.arctan2(mu_y_fit, mu_x_fit)))
            except Exception:
                theta_gauss = np.nan
            t_gauss_elapsed = time.time() - t0_gauss

        # -------------------------------------------------------------
        # Consolidated Benchmark Table Output
        # -------------------------------------------------------------
        if self.rank == 0:
            print("\n" + "=" * 88)
            print(f"{'ALGORITHM / METHOD':<36} | {'RECON ANGLE (°)':<16} | {'BIAS (°)':<12} | {'TIME (s)':<10} | {'STATUS':<6}")
            print("=" * 88)

            def print_row(name, theta_recon, t_el):
                bias = theta_recon - target_angle
                status = "OK" if not np.isnan(theta_recon) else "FAIL"
                print(f"{name:<36} | {theta_recon:<16.3f} | {bias:<+12.3f} | {t_el:<10.4f} | {status:<6}")

            print_row("1. Discrete FND (Argmin Grid)", theta_fnd_argmin, t_fnd_elapsed)
            print_row("2. Continuous FND (|Sin| Fit)", theta_fnd_sine, t_fnd_elapsed)
            print_row("3. Centroid Vector Sum", theta_centroid, t_centroid_elapsed)
            print_row("4. 2D Gaussian Surface Fit", theta_gauss, t_gauss_elapsed)
            print("=" * 88 + "\n")

        self.comm.Barrier()
    def gaussHist2D(self, save=False):
        if self.debug_L1:
            print("DataProcessor class method: gaussHist2D")

        """
        This is a nonparallel subroutine that runs on the host core. It plots a 2D histogram of a sample of the neutron data as a 3D bar plot.
        """

        # Take a given sample of the data.
        data = self.sampleData(self.n)
        x, y = data[:, 0], data[:, 1]

        # Produce the histogram.
        hist, xedges, yedges = np.histogram2d(y, x, bins=self.grid_size, range=[self.x_range, self.y_range])

        # Build grid positions.
        half = self.grid_size // 2
        x = (np.arange(self.grid_size) - half) * self.seg_size
        y = (np.arange(self.grid_size) - half) * self.seg_size
        xpos, ypos = np.meshgrid(x, y, indexing="ij")

        # Flatten for 3D bar plot.
        xpos = xpos.ravel()
        ypos = ypos.ravel()
        zpos = np.zeros_like(xpos)

        dz = hist.ravel()
        dx = dy = np.full_like(zpos, self.seg_size)

        # Plot.
        fig = plt.figure()
        ax = fig.add_subplot(111, projection="3d", facecolor="white")

        ax.set_facecolor("white")

        ax.bar3d(xpos - self.seg_size / 2, ypos - self.seg_size / 2, zpos, dx, dy, dz, shade=True, color="skyblue", edgecolor="black")

        # Label axes.
        ax.set_xlabel("$x$ (mm)")
        ax.set_ylabel("$y$ (mm)")
        ax.set_zlabel("Counts")

        # Set tick marks to match the coordinates.
        tick_labels = [-150, 0, 150]
        ax.set_xticks(tick_labels)
        ax.set_yticks(tick_labels)
        ax.set_xticklabels([str(t) for t in tick_labels])
        ax.set_yticklabels([str(t) for t in tick_labels])

        # Adjust the elevation and azimuth for a nice view.
        ax.view_init(elev=10, azim=30)

        if save:
            plt.savefig(f"LEGO_dx_{self.seg_size}_n_{self.n}.pdf", format="pdf")

        plt.tight_layout()
        plt.show()

        return

