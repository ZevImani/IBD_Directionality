    def round_to_nearest_odd(self, x):

        # Round to nearest integer.
        n = round(x)

        if n % 2 == 0:
            # # If it's even choose the closer odd: n-1 or n+1.
            if abs(x - (n - 1)) <= abs(x - (n + 1)):
                return n - 1
            else:
                return n + 1
        return n

