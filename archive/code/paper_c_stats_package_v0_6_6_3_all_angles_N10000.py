    def run_statistical_suite(self, meas_angle=10.0, ref_A_angle=0.0, ref_B_angle=45.0, n_sample=10000):
        # Explicit method-level imports ensuring scope resolution across execution contexts
        from scipy.stats import ks_2samp, chisquare, anderson, permutation_test, wasserstein_distance
        from scipy.special import rel_entr
        from scipy.spatial.distance import jensenshannon, mahalanobis
        from astropy.stats import kuiper_two
        try:
            from pycircstat2 import Circular
            from pycircstat2.hypothesis import V_test, watson_u2_test
            has_circ = True
        except ImportError:
            has_circ = False
        """
        Executes the 12-test distribution-free statistical suite comparing an empirical
        binned measurement against rotated reference templates without functional assumptions.
        NOTE: v0-6-3-1 2026-09-27 'Integrated July v0-5 statistical testing suite into DataProcessor'
        """
        if self.rank != 0:
            self.comm.Barrier()
            return

        print(f"\n=== Running Statistical Testing Suite (N = {n_sample}) ===")
        print(f"Target Measurement Angle: {meas_angle} deg | Template A: {ref_A_angle} deg | Template B: {ref_B_angle} deg")

        # 1. Draw independent samples from in-memory usable coordinates
        sample_meas = self.sampleData(n_sample, center=False)
        sample_A    = self.sampleData(n_sample, center=False)
        sample_B    = self.sampleData(n_sample, center=False)

        # 2. Rotate samples into respective frames
        xm, ym = self.rotateCoords(sample_meas[:, 0], sample_meas[:, 1], meas_angle)
        xa, ya = self.rotateCoords(sample_A[:, 0], sample_A[:, 1], ref_A_angle)
        xb, yb = self.rotateCoords(sample_B[:, 0], sample_B[:, 1], ref_B_angle)

        # 3. Bin into 2D spatial matrices
        grid_M = self.binEvents(xm, ym) * n_sample
        grid_A = self.binEvents(xa, ya) * n_sample
        grid_B = self.binEvents(xb, yb) * n_sample

        # 4. Gabe's Cartesian-to-polar topological alignment: rot90 + roll(-1)
        flat_M = np.roll(np.rot90(grid_M).ravel(), -1)
        flat_A = np.roll(np.rot90(grid_A).ravel(), -1)
        flat_B = np.roll(np.rot90(grid_B).ravel(), -1)

        # 5. Normalization with Laplace/epsilon smoothing (1e-6) for stable entropy/chi2
        norm_M = (flat_M / np.sum(flat_M)) + 1e-6
        norm_A = (flat_A / np.sum(flat_A)) + 1e-6
        norm_B = (flat_B / np.sum(flat_B)) + 1e-6

        def bhattacharyya_dist(p, q):
            return -np.log(np.sum(np.sqrt(p * q)))

        def stat_diff_means(d1, d2, axis=0):
            return np.mean(d1, axis=axis) - np.mean(d2, axis=axis)

        print("\n" + "=" * 82)
        print(f"{'STATISTICAL TEST / METRIC':<36} | {f'VS A ({ref_A_angle:.0f}°)':<18} | {f'VS B ({ref_B_angle:.0f}°)':<18}")
        print("=" * 82)

        # 1. Kuiper Two-Sample Test
        k_stat_A, k_p_A = kuiper_two(flat_M, flat_A)
        k_stat_B, k_p_B = kuiper_two(flat_M, flat_B)
        print(f"{'1.  Kuiper Two-Sample (stat, p-val)':<36} | {k_stat_A:.4f}, p={k_p_A:.3e}  | {k_stat_B:.4f}, p={k_p_B:.3e}")

        # 2. Kolmogorov-Smirnov Test
        ks_A = ks_2samp(flat_M, flat_A)
        ks_B = ks_2samp(flat_M, flat_B)
        print(f"{'2.  Kolmogorov-Smirnov (stat, p-val)':<36} | {ks_A.statistic:.4f}, p={ks_A.pvalue:.3e}  | {ks_B.statistic:.4f}, p={ks_B.pvalue:.3e}")

        # 3. Chi-Squared Goodness of Fit
        chi_A = chisquare(f_obs=norm_M, f_exp=norm_A)
        chi_B = chisquare(f_obs=norm_M, f_exp=norm_B)
        print(f"{'3.  Chi-Squared (stat, p-val)':<36} | {chi_A.statistic:.4f}, p={chi_A.pvalue:.3e}  | {chi_B.statistic:.4f}, p={chi_B.pvalue:.3e}")

        # 4. Earth Mover's Distance (Wasserstein)
        emd_A = wasserstein_distance(flat_M, flat_A)
        emd_B = wasserstein_distance(flat_M, flat_B)
        print(f"{'4.  Wasserstein Distance (EMD)':<36} | {emd_A:<18.4f} | {emd_B:<18.4f}")

        # 5. Kullback-Leibler Divergence
        kl_A = np.sum(rel_entr(norm_M, norm_A))
        kl_B = np.sum(rel_entr(norm_M, norm_B))
        print(f"{'5.  Kullback-Leibler Divergence':<36} | {kl_A:<18.6f} | {kl_B:<18.6f}")

        # 6. Jensen-Shannon Divergence
        js_A = jensenshannon(norm_M, norm_A)
        js_B = jensenshannon(norm_M, norm_B)
        print(f"{'6.  Jensen-Shannon Divergence':<36} | {js_A:<18.6f} | {js_B:<18.6f}")

        # 7. Bhattacharyya Distance
        bh_A = bhattacharyya_dist(norm_M, norm_A)
        bh_B = bhattacharyya_dist(norm_M, norm_B)
        print(f"{'7.  Bhattacharyya Distance':<36} | {bh_A:<18.6f} | {bh_B:<18.6f}")

        # 8. Permutation Test (Mean Difference)
        perm_A = permutation_test((flat_M, flat_A), stat_diff_means, n_resamples=1000)
        perm_B = permutation_test((flat_M, flat_B), stat_diff_means, n_resamples=1000)
        print(f"{'8.  Permutation Test (stat, p-val)':<36} | {perm_A.statistic:.4f}, p={perm_A.pvalue:.3e}  | {perm_B.statistic:.4f}, p={perm_B.pvalue:.3e}")

        # 9. Mahalanobis Distance (Covariance-weighted)
        cov_A = np.cov(grid_M, rowvar=False) + np.eye(self.grid_size) * 1e-4
        cov_inv_A = np.linalg.pinv(cov_A)
        maha_A = mahalanobis(flat_M[:self.grid_size], flat_A[:self.grid_size], cov_inv_A)
        maha_B = mahalanobis(flat_M[:self.grid_size], flat_B[:self.grid_size], cov_inv_A)
        print(f"{'9.  Mahalanobis Distance':<36} | {maha_A:<18.4f} | {maha_B:<18.4f}")

        # 10. Anderson-Darling Test (Empirical tail distribution)
        ad_M = anderson(flat_M)
        ad_A = anderson(flat_A)
        ad_B = anderson(flat_B)
        print(f"{'10. Anderson-Darling Stat (M / A / B)':<36} | {ad_M.statistic:.4f} / {ad_A.statistic:.4f}     | {ad_B.statistic:.4f}")

        # 11 & 12. Circular Statistics (V-Test and Watson U2)
        if has_circ:
            try:
                def extract_stat_pval(res):
                    stat = getattr(res, 'statistic', getattr(res, 'V', getattr(res, 'u2', getattr(res, 'U2', None))))
                    pval = getattr(res, 'pvalue', getattr(res, 'p_value', getattr(res, 'pval', getattr(res, 'p', None))))
                    if stat is None and isinstance(res, (tuple, list)):
                        stat = res[0]
                        pval = res[-1]
                    return float(stat) if stat is not None else np.nan, float(pval) if pval is not None else np.nan

                # 11. Circular V-Test vs 0 deg
                c_M = Circular(data=np.deg2rad(flat_M))
                res_V = V_test(angle=0.0, alpha=c_M.alpha, verbose=False)
                V_stat, V_pval = extract_stat_pval(res_V)
                print(f"{'11. Circular V-Test vs 0° (stat, p-val)':<36} | V={V_stat:.4f}, p={V_pval:.3e}     | -")

                # 12. Watson U2 Circular Test (using integer event weights)
                angles_circ = np.linspace(0, 2 * np.pi, len(flat_M), endpoint=False)
                w_M = np.maximum(0, flat_M.astype(int))
                w_A = np.maximum(0, flat_A.astype(int))
                w_B = np.maximum(0, flat_B.astype(int))

                df_M = pd.DataFrame({'theta': np.repeat(angles_circ, w_M)})
                df_A = pd.DataFrame({'theta': np.repeat(angles_circ, w_A)})
                df_B = pd.DataFrame({'theta': np.repeat(angles_circ, w_B)})

                circ_M = Circular(data=df_M['theta'].values)
                circ_A = Circular(data=df_A['theta'].values)
                circ_B = Circular(data=df_B['theta'].values)

                res_u2_A = watson_u2_test([circ_M, circ_A])
                res_u2_B = watson_u2_test([circ_M, circ_B])

                u2_A_stat, u2_A_pval = extract_stat_pval(res_u2_A)
                u2_B_stat, u2_B_pval = extract_stat_pval(res_u2_B)

                print(f"{'12. Watson U² Circular (stat, p-val)':<36} | {u2_A_stat:.4f}, p={u2_A_pval:.3e}    | {u2_B_stat:.4f}, p={u2_B_pval:.3e}")
            except Exception as e:
                print(f"{'11/12. Circular Suite (V / Watson)':<36} | Error: {e}")
        else:
            print(f"{'11/12. Circular Suite (V / Watson)':<36} | Skipped (pycircstat2 not found)")

        print("=" * 82)
        print()
        self.comm.Barrier()

    def gaussian_2d(self, coords, A, mu_x, mu_y, sigma_x, sigma_y):
        x, y = coords
        return A * np.exp(-((x - mu_x)**2 / (2 * sigma_x**2) + (y - mu_y)**2 / (2 * sigma_y**2)))

    def get_disjoint_sample(self, n_sample, batch_idx=0):
        """
        Extracts strictly non-overlapping event batches to guarantee zero cross-iteration covariance.
        """
        pool = self.usable_coords
        total_available = len(pool)
        k_max = total_available // n_sample
        if batch_idx >= k_max:
            # Wrap with warning indicator if pool is exhausted
            start_idx = (batch_idx * n_sample) % max(1, total_available - n_sample)
        else:
            start_idx = batch_idx * n_sample
        return pool[start_idx : start_idx + n_sample]

    def evaluate_12_tests(self, flat_M, flat_A, flat_B, grid_M):
        """
        Evaluates 12 distribution-free tests with defensive guards for N in [1, 10, 100].
        Catches rank deficiencies, empty-bin zero divisions, and permutation bounds.
        """
        from scipy.stats import ks_2samp, chisquare, anderson, permutation_test, wasserstein_distance
        from scipy.special import rel_entr
        from scipy.spatial.distance import jensenshannon, mahalanobis
        from astropy.stats import kuiper_two
        try:
            from pycircstat2 import Circular
            from pycircstat2.hypothesis import V_test, watson_u2_test
            has_circ = True
        except ImportError:
            has_circ = False

        sum_M = np.sum(flat_M)
        sum_A = np.sum(flat_A)
        sum_B = np.sum(flat_B)

        norm_M = (flat_M / (sum_M if sum_M > 0 else 1.0)) + 1e-6
        norm_A = (flat_A / (sum_A if sum_A > 0 else 1.0)) + 1e-6
        norm_B = (flat_B / (sum_B if sum_B > 0 else 1.0)) + 1e-6

        def bhatta(p, q):
            val = np.sum(np.sqrt(p * q))
            return -np.log(val) if val > 0 else 999.0

        def stat_diff(d1, d2, axis=0):
            return np.mean(d1, axis=axis) - np.mean(d2, axis=axis)

        res = {}
        # 1. Kuiper (safe against overflow)
        try:
            k_s_A, k_p_A = kuiper_two(flat_M, flat_A)
        except Exception:
            k_s_A, k_p_A = np.nan, np.nan
        try:
            k_s_B, k_p_B = kuiper_two(flat_M, flat_B)
        except Exception:
            k_s_B, k_p_B = np.nan, np.nan
        res['kuiper'] = (k_s_A, k_p_A, k_s_B, k_p_B)

        # 2. KS
        try:
            res['ks'] = (ks_2samp(flat_M, flat_A).statistic, ks_2samp(flat_M, flat_A).pvalue,
                         ks_2samp(flat_M, flat_B).statistic, ks_2samp(flat_M, flat_B).pvalue)
        except Exception:
            res['ks'] = (np.nan, np.nan, np.nan, np.nan)

        # 3. Chi2
        try:
            res['chi2'] = (chisquare(f_obs=norm_M, f_exp=norm_A).statistic, chisquare(f_obs=norm_M, f_exp=norm_A).pvalue,
                           chisquare(f_obs=norm_M, f_exp=norm_B).statistic, chisquare(f_obs=norm_M, f_exp=norm_B).pvalue)
        except Exception:
            res['chi2'] = (np.nan, np.nan, np.nan, np.nan)

        # 4. EMD
        try:
            res['emd'] = (wasserstein_distance(flat_M, flat_A), wasserstein_distance(flat_M, flat_B))
        except Exception:
            res['emd'] = (np.nan, np.nan)

        # 5. KL Divergence
        try:
            res['kl'] = (np.sum(rel_entr(norm_M, norm_A)), np.sum(rel_entr(norm_M, norm_B)))
        except Exception:
            res['kl'] = (np.nan, np.nan)

        # 6. JS Divergence
        try:
            res['js'] = (jensenshannon(norm_M, norm_A), jensenshannon(norm_M, norm_B))
        except Exception:
            res['js'] = (np.nan, np.nan)

        # 7. Bhattacharyya
        res['bhatta'] = (bhatta(norm_M, norm_A), bhatta(norm_M, norm_B))

        # 8. Permutation
        try:
            if sum_M > 1:
                p_A = permutation_test((flat_M, flat_A), stat_diff, n_resamples=500)
                p_B = permutation_test((flat_M, flat_B), stat_diff, n_resamples=500)
                res['perm'] = (p_A.statistic, p_A.pvalue, p_B.statistic, p_B.pvalue)
            else:
                res['perm'] = (0.0, 1.0, 0.0, 1.0)
        except Exception:
            res['perm'] = (np.nan, np.nan, np.nan, np.nan)

        # 9. Mahalanobis
        try:
            if self.grid_size <= 9 and sum_M > 2:
                cov_A = np.cov(grid_M, rowvar=False) + np.eye(self.grid_size) * 1e-3
                cov_inv_A = np.linalg.pinv(cov_A)
                m_len = min(self.grid_size, len(flat_M))
                res['maha'] = (mahalanobis(flat_M[:m_len], flat_A[:m_len], cov_inv_A[:m_len, :m_len]),
                               mahalanobis(flat_M[:m_len], flat_B[:m_len], cov_inv_A[:m_len, :m_len]))
            else:
                res['maha'] = (0.0, 0.0)
        except Exception:
            res['maha'] = (np.nan, np.nan)

        # 10. Anderson-Darling
        try:
            res['ad'] = (anderson(flat_M).statistic, anderson(flat_A).statistic, anderson(flat_B).statistic)
        except Exception:
            res['ad'] = (np.nan, np.nan, np.nan)

        # 11 & 12. Circular
        if has_circ and sum_M > 0:
            try:
                def get_stat(r, default_val=np.nan):
                    s = getattr(r, 'statistic', getattr(r, 'V', getattr(r, 'u2', getattr(r, 'U2', None))))
                    if s is None and isinstance(r, (tuple, list)):
                        s = r[0]
                    return float(s) if s is not None else default_val

                c_M = Circular(data=np.deg2rad(flat_M), kwargs_median={'method': None})
                res['vtest'] = (get_stat(V_test(angle=0.0, alpha=c_M.alpha, verbose=False)), 0.0)

                angles_c = np.linspace(0, 2 * np.pi, len(flat_M), endpoint=False)
                w_M = np.maximum(0, flat_M.astype(int))
                w_A = np.maximum(0, flat_A.astype(int))
                w_B = np.maximum(0, flat_B.astype(int))

                cM = Circular(data=np.repeat(angles_c, w_M), kwargs_median={'method': None})
                cA = Circular(data=np.repeat(angles_c, w_A), kwargs_median={'method': None})
                cB = Circular(data=np.repeat(angles_c, w_B), kwargs_median={'method': None})

                res['watson'] = (get_stat(watson_u2_test([cM, cA])), 0.0,
                                 get_stat(watson_u2_test([cM, cB])), 0.0)
            except Exception:
                res['vtest'] = (np.nan, np.nan)
                res['watson'] = (np.nan, np.nan, np.nan, np.nan)
        else:
            res['vtest'] = (np.nan, np.nan)
            res['watson'] = (np.nan, np.nan, np.nan, np.nan)

        return res

